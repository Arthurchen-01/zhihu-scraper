def get_essay_by_preset(aid: str, preset: str = "random_all") -> Dict[str, Any]:
    """根据指定预设和文章 ID 哈希，获取高价值替换内容"""
    pool = ALL_ESSAYS
    if preset == "law":
        pool = LAW_ESSAYS
    elif preset == "classics":
        pool = CLASSIC_ESSAYS
    elif preset == "random_all":
        pool = ALL_ESSAYS
    
    idx = int(hashlib.md5(str(aid).encode("utf-8")).hexdigest(), 16) % len(pool)
    return pool[idx]
